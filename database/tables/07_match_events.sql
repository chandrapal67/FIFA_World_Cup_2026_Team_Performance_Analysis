-- ============================================================
-- FIFA WORLD CUP 2026
-- TABLE: MATCH_EVENTS
-- ============================================================
-- Purpose:
-- Stores meaningful player-related match events from the
-- FIFA World Cup 2026, including goals, own goals, penalty
-- goals, substitutions and disciplinary cards.
--
-- Event minutes are stored as VARCHAR to support FIFA formats
-- such as 45+1 and 90+6, as well as HT for certain
-- halftime substitutions.
-- ============================================================

CREATE TABLE match_events (
    event_id INT PRIMARY KEY,
    match_id INT NOT NULL,
    team_id INT NOT NULL,
    player_id INT,
    substitute_player_id INT,
    event_type VARCHAR(30) NOT NULL,
    event_minute VARCHAR(10) NOT NULL,

    FOREIGN KEY (match_id) REFERENCES matches(match_id),
    FOREIGN KEY (team_id) REFERENCES teams(team_id),
    FOREIGN KEY (player_id) REFERENCES players(player_id),
    FOREIGN KEY (substitute_player_id) REFERENCES players(player_id)
);

