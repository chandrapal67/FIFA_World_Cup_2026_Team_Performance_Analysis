-- ============================================================
-- FIFA WORLD CUP 2026
-- TABLE: MATCHES
-- ============================================================
-- Purpose:
-- Stores FIFA World Cup 2026 match information including
-- date, stage, venue, participating teams, scores,
-- penalty scores, attendance and match status.
-- ============================================================

CREATE TABLE matches (
    match_id INT PRIMARY KEY,
    match_date DATE NOT NULL,
    stage VARCHAR(30) NOT NULL,
    venue_id INT NOT NULL,
    home_team_id INT NOT NULL,
    away_team_id INT NOT NULL,
    home_score TINYINT NOT NULL,
    away_score TINYINT NOT NULL,
    home_penalty_score TINYINT,
    away_penalty_score TINYINT,
    attendance INT,
    status VARCHAR(20) NOT NULL,

    FOREIGN KEY (venue_id)
        REFERENCES venues(venue_id),

    FOREIGN KEY (home_team_id)
        REFERENCES teams(team_id),

    FOREIGN KEY (away_team_id)
        REFERENCES teams(team_id)
);

